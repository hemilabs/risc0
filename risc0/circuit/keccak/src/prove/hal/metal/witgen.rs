//! Witness generation of the keccak circuit on the Metal HAL (items K2, K6).
//!
//! - `scatter_preflight` runs the `scatter_preflight` kernel (kernels/metal/scatter.metal, a 1:1
//!   port of kernels/cuda/ffi.cu `scatter_preflight`), as `CudaCircuitHal::scatter_preflight`
//!   does, into the `data` buffer the prover allocated (INVALID-filled).
//! - `generate_witness` (parallel mode) runs the GPU witness generator (K6): CUDA's
//!   `par_stepExec` (one thread per cycle running the whole `step_Top` tree) split into one
//!   kernel per arm of `step_Top`, `step_arm_<K>` (generated by keccak-sys/build_metal_witgen.rs
//!   into the keccak metallib). The cycles are grouped by (cycle_type, sub_type), the
//!   [MetalPreflightOrder] buckets, and each group is one dispatch of its cycle type's arm kernel,
//!   all in one command buffer; a fault flag turns CUDA's asserts (inconsistent set, read of an
//!   unset cell) into `Err`. Below po2 13 (where the CPU is faster), in the sequential modes
//!   (`fwd_rev_ab` only) and with `RISC0_KECCAK_METAL_WITGEN=host`, the CPU witness generator
//!   (kernels/cxx) writes the HAL's shared buffers instead, as K2 did for every mode.

