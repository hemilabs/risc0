"""CUDA -> Metal translator for the recursion circuit's generated step functions (Metal port
item C2, plan 4.3 "steps mode", errata 8.2/8.3).

usage:
  cuda2metal_steps.py -o OUTDIR [--check] [--no-pin] [--compile] [--metallib PATH]
                      [--define NAME=VALUE ...] [--only NAME ...] [--step-exec-src SPLIT.cu]
  cuda2metal_steps.py --check            # round trip + pins only, nothing written
  cuda2metal_steps.py --list-kernels     # the kernel entry names, one per line

Inputs (kernels/cuda, generated by zirgen; checked in) -> outputs (OUTDIR, never checked in):
  step_exec.cu          -> step_exec.metal          + kernel parStepExec
  step_verify_mem.cu    -> step_verify_mem.metal    + kernel parStepVerifyWom
  step_compute_accum.cu -> step_compute_accum.metal + kernel parStepComputeAccum
  step_verify_accum.cu  -> step_verify_accum.metal  + kernel parStepVerifyAccum
step_verify_bytes.cu is skipped: its step function is empty and no kernel calls it (errata 8.3).

step_exec.cu is zirgen's monolith (risc0 3.1; the 3.0 fork checked in a split form). The
translation input is its 19-arm `__noinline__` split made by split_step_exec_metal.py (P31-07):
build.rs writes it to $OUT_DIR and passes `--step-exec-src`; without that option this script
splits kernels/cuda/step_exec.cu in memory with the same generator. `--check`'s round trip
compares with the split text.

Rewrites (each a reversible `Rule` from cuda2metal_common.py, counted and pinned in PINNED):
  include          #include "extern.cuh" -> #include "extern.h" (kernels/metal, item C1: the
                   thread ExecCtx/AccumCtx contexts and the clamped extern handlers).
  qual.noinline    `__device__ __noinline__ void` -> `static __attribute__((noinline)) void`
                   (the 19 step_exec arms of the split, declared and defined: 38).
  qual.device_fn   `__device__ void step_*(` -> `static inline void step_*(`.
  ctx_param        `void* ctx,` -> `thread ExecCtx* ctx,` (exec, verify_mem) or
                   `thread AccumCtx* ctx,` (accum).
  arg_param        `Fp* argN` -> `device Fp* argN` (parameters only; calls pass names).
  device_auto_ref  `auto& reg = argN[...]` -> `device auto& reg = ...`.
  assert           `assert(E);` -> `ctx->bad |= !(E);` (plan 2.9: CUDA's device assert aborts the
                   grid; here the thread records the fault and the wrapper ORs it into `fault`
                   once at the end; the witness of a valid trace is unchanged).
  fp_zero          `xN = 0;` -> `xN = Fp(0);` (mandatory: `= 0` is ambiguous between fp.h's
                   `operator=(uint32_t)` and the implicit copy from `Fp(uint32_t)`).
  trap             `if (c1_bad) __trap();` -> `ctx->bad |= c1_bad;` (the accum steps' branch-free
                   assert; the c1_bad accumulation itself is plain C and passes through).

`--check` translates in memory, checks the pins, runs the residual scan and the round trip
(strip the generated blocks, undo every rule in reverse order, compare with the CUDA source byte
for byte), and, when OUTDIR holds outputs, compares them too. `--compile` compiles every output
with `xcrun metal -std=metal3.2 -O2` (include path: build_kernel/kernels/metal and
recursion-sys/kernels/metal only) and, with --metallib, links them.

`--define C2M_PSO_NONCE=N` adds a never-taken compare on an unused params pad word to every
wrapper, so a metallib with fresh content can be produced to time cold PSO creation past the
OS shader cache. Production builds never define it.
"""

import argparse
import os
import re
import sys

sys.dont_write_bytecode = True  # never leave __pycache__ in the source tree (build.rs runs this)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cuda2metal_common as c  # noqa: E402
import split_step_exec_metal  # noqa: E402

TG_SIZE = 256

# Kernel binding orders: kernels/metal/context.h (item C1), `ExecCtx` and `AccumCtx` comments.
EXEC_BINDINGS = """\
// buffer(0) ctrl      device Fp*              ctrl columns (CUDA ExecBuffers::ctrl)
// buffer(1) data      device Fp*              data columns (ExecBuffers::data)
// buffer(2) global    device Fp*              globals (ExecBuffers::global)
// buffer(3) wom       const device FpExt*     PreflightTrace::wom    (numWoms)
// buffer(4) cycles    device PreflightCycle*  PreflightTrace::cycles (numCycles)
// buffer(5) iops      const device FpExt*     PreflightTrace::iops   (numIops)
// buffer(6) womRows   device WomArgumentRow*  ExecContext::womRows   (numWomRows)
// buffer(7) womIndex  device uint32_t*        ExecContext::womIndex  (numCycles)
// buffer(8) fault     device atomic_uint*     ORed with the thread's ctx.bad once at the end
// buffer(9) params    constant RecExecParams& (set_bytes)
"""

ACCUM_BINDINGS = """\
// buffer(0) ctrl      device Fp*              (CUDA AccumBuffers::ctrl)
// buffer(1) global    device Fp*              (AccumBuffers::global)
// buffer(2) data      device Fp*              (AccumBuffers::data)
// buffer(3) mix       device Fp*              (AccumBuffers::mix)
// buffer(4) accum     device Fp*              the accum column group (AccumBuffers::accum)
// buffer(5) accumTmp  device FpExt*           per-cycle scratch (AccumContext::accum, workCycles)
// buffer(6) fault     device atomic_uint*     ORed with the thread's ctx.bad once at the end
// buffer(7) params    constant RecAccumParams& (set_bytes)
"""

EXEC_SIG = """\
    device Fp* ctrl [[buffer(0)]],
    device Fp* data [[buffer(1)]],
    device Fp* global [[buffer(2)]],
    const device FpExt* wom [[buffer(3)]],
    device PreflightCycle* cycles [[buffer(4)]],
    const device FpExt* iops [[buffer(5)]],
    device WomArgumentRow* womRows [[buffer(6)]],
    device uint32_t* womIndex [[buffer(7)]],
    device metal::atomic_uint* fault [[buffer(8)]],
    constant RecExecParams& params [[buffer(9)]],
    uint gid [[thread_position_in_grid]]"""

ACCUM_SIG = """\
    device Fp* ctrl [[buffer(0)]],
    device Fp* global [[buffer(1)]],
    device Fp* data [[buffer(2)]],
    device Fp* mix [[buffer(3)]],
    device Fp* accum [[buffer(4)]],
    device FpExt* accumTmp [[buffer(5)]],
    device metal::atomic_uint* fault [[buffer(6)]],
    constant RecAccumParams& params [[buffer(7)]],
    uint gid [[thread_position_in_grid]]"""

EXEC_CTX = ('  ExecCtx ctx = make_exec_ctx(ctrl, data, global, wom, cycles, iops, womRows, '
            'womIndex, params);\n')
ACCUM_CTX = '  AccumCtx ctx = make_accum_ctx(ctrl, global, data, mix, accum, accumTmp, params);\n'

NONCE = """\
#ifdef C2M_PSO_NONCE
  // Cold-PSO timing only (never defined in builds): a distinct binary per nonce.
  if (params.%s == uint32_t(C2M_PSO_NONCE)) ctx.bad |= 0x40000000u;
#endif
"""

# A count guard shared by the wrappers: a trace with more cycles than rows would index past the
# columns (CUDA trusts the host here; plan 2.9 makes it a fault).
EXEC_GUARD = """\
  if (params.numCycles > params.totalCycles) {
    if (gid == 0) r0_fault_flush(fault, 1u);
    return;
  }
"""
ACCUM_GUARD = """\
  if (params.workCycles > params.totalCycles) {
    if (gid == 0) r0_fault_flush(fault, 1u);
    return;
  }
"""


def wrapper(name, bindings, sig, guard, body, cuda_ref):
    return ("// Kernel %s (CUDA %s): one thread per cycle; dispatch with\n"
            "// Grid::Threads(n) (a 1-D grid, any threadgroup size up to %d).\n"
            "%s"
            "[[max_total_threads_per_threadgroup(%d)]]\n"
            "kernel void %s(\n%s) {\n%s%s}\n"
            % (name, cuda_ref, TG_SIZE, bindings, TG_SIZE, name, sig, guard, body))


PAR_STEP_EXEC = wrapper(
    'parStepExec', EXEC_BINDINGS, EXEC_SIG, EXEC_GUARD,
    "  uint32_t count = params.numCycles;\n"
    "  // isParSafe == 2 marks the head of a chain whose rows the host already computed.\n"
    "  if (gid >= count || cycles[gid].isParSafe == 2) return;\n"
    + EXEC_CTX + NONCE % '_pad2' +
    "  // nextStepExec: a parallel-safe row (or row 0) runs itself and the sequential rows after\n"
    "  // it (isParSafe == 0) up to the next parallel-safe row.\n"
    "  uint32_t cycle = gid;\n"
    "  if (cycle == 0 || ctx.isParSafeExec(cycle)) {\n"
    "    step_exec(&ctx, ctx.totalCycles, cycle++, ctrl, global, data, nullptr, nullptr);\n"
    "    while (cycle < count && !ctx.isParSafeExec(cycle)) {\n"
    "      step_exec(&ctx, ctx.totalCycles, cycle++, ctrl, global, data, nullptr, nullptr);\n"
    "    }\n"
    "  }\n"
    "  r0_fault_flush(fault, ctx.bad);\n",
    'ffi.cu parStepExec + nextStepExec')

PAR_STEP_VERIFY_WOM = wrapper(
    'parStepVerifyWom', EXEC_BINDINGS, EXEC_SIG, EXEC_GUARD,
    "  if (gid >= params.numCycles) return;\n"
    + EXEC_CTX + NONCE % '_pad2' +
    "  step_verify_mem(&ctx, ctx.totalCycles, gid, ctrl, global, data, nullptr, nullptr);\n"
    "  r0_fault_flush(fault, ctx.bad);\n",
    'ffi.cu parStepVerifyWom')

PAR_STEP_COMPUTE_ACCUM = wrapper(
    'parStepComputeAccum', ACCUM_BINDINGS, ACCUM_SIG, ACCUM_GUARD,
    "  if (gid >= params.workCycles) return;\n"
    + ACCUM_CTX + NONCE % '_pad1' +
    "  step_compute_accum(&ctx, ctx.totalCycles, gid, ctrl, global, data, mix, accum);\n"
    "  r0_fault_flush(fault, ctx.bad);\n",
    'ffi.cu parStepComputeAccum')

PAR_STEP_VERIFY_ACCUM = wrapper(
    'parStepVerifyAccum', ACCUM_BINDINGS, ACCUM_SIG, ACCUM_GUARD,
    "  if (gid >= params.workCycles) return;\n"
    + ACCUM_CTX + NONCE % '_pad1' +
    "  step_verify_accum(&ctx, ctx.totalCycles, gid, ctrl, global, data, mix, accum);\n"
    "  r0_fault_flush(fault, ctx.bad);\n",
    'ffi.cu parStepVerifyAccum')

FILES = {
    'step_exec': dict(ctx='ExecCtx', kernel='parStepExec', wrapper=PAR_STEP_EXEC),
    'step_verify_mem': dict(ctx='ExecCtx', kernel='parStepVerifyWom', wrapper=PAR_STEP_VERIFY_WOM),
    'step_compute_accum': dict(ctx='AccumCtx', kernel='parStepComputeAccum',
                               wrapper=PAR_STEP_COMPUTE_ACCUM),
    'step_verify_accum': dict(ctx='AccumCtx', kernel='parStepVerifyAccum',
                              wrapper=PAR_STEP_VERIFY_ACCUM),
}
SKIPPED = ['step_verify_bytes']

KERNEL_NAMES = [FILES[f]['kernel'] for f in FILES]

# Rewrite counts for the checked-in generated sources (plan 4.3 row C2: 51 Fp(0), 4373 + 960
# asserts, 1768 device auto& in step_exec, 38 noinline, 486 + 329 c1_bad, 2 trap). A change means
# zirgen's output changed shape: run with --no-pin, review the output and its compile, update.
# Rule keys are rewrites; `tally.*` keys count constructs that pass through unchanged.
# risc0 3.1 (P31-07, notes/P31-07.md): step_exec assert 4373 -> 4375 and device_auto_ref
# 1768 -> 1770. zirgen 540bcee's BIT_AND_ELEM fix (84a449919, canonical bit decompositions) makes
# data offsets 5/6 (`top_a`/`top_b`) computed witnesses: step_exec_macro_bit_and_elem gains two
# guarded writes per offset (4 x `auto& reg = arg2[5|6 * steps + cycle]; assert(reg ==
# Fp::invalid() || reg == x); reg = x;`), and the macro_ops tail loses its two default writes of
# the same offsets: +4 - 2 = +2 auto&, +2 asserts (the monolith moves 4378 -> 4380 the same way).
# Every other count, and the other three files, are unchanged.
PINNED = {
    'step_exec': {
        'include': 1, 'qual.noinline': 38, 'qual.device_fn': 1, 'ctx_param': 39,
        'arg_param': 119, 'device_auto_ref': 1770, 'assert': 4375, 'fp_zero': 51,
        'tally.assert_msg': 0, 'tally.extern_call': 275, 'tally.c1_bad': 0, 'wrapper': 1,
    },
    'step_verify_mem': {
        'include': 1, 'ctx_param': 1, 'qual.device_fn': 1, 'arg_param': 5,
        'device_auto_ref': 250, 'assert': 960, 'tally.assert_msg': 240,
        'tally.extern_call': 47, 'tally.c1_bad': 0, 'wrapper': 1,
    },
    'step_compute_accum': {
        'include': 1, 'ctx_param': 1, 'qual.device_fn': 1, 'arg_param': 5, 'trap': 1,
        'tally.extern_call': 13, 'tally.c1_bad': 486, 'wrapper': 1,
    },
    'step_verify_accum': {
        'include': 1, 'ctx_param': 1, 'qual.device_fn': 1, 'arg_param': 5,
        'device_auto_ref': 92, 'trap': 1, 'tally.extern_call': 13, 'tally.c1_bad': 329,
        'wrapper': 1,
    },
}


def rules_for(ctx_type):
    return [
        c.Rule('include', r'^#include "extern\.cuh"$', '#include "extern.h"',
               r'^#include "extern\.h"$', '#include "extern.cuh"'),
        c.Rule('qual.noinline', r'__device__ __noinline__ void ',
               'static __attribute__((noinline)) void ',
               r'static __attribute__\(\(noinline\)\) void ', '__device__ __noinline__ void '),
        c.Rule('qual.device_fn', r'^__device__ void (step_\w+)\(', r'static inline void \1(',
               r'^static inline void (step_\w+)\(', r'__device__ void \1('),
        c.Rule('ctx_param', r'\bvoid\* ctx,', 'thread %s* ctx,' % ctx_type,
               r'\bthread %s\* ctx,' % ctx_type, 'void* ctx,',
               collision=r'\bthread \w+\* ctx,'),
        c.Rule('arg_param', r'(?<![\w*])Fp\* (arg\d)\b', r'device Fp* \1',
               r'\bdevice Fp\* (arg\d)\b', r'Fp* \1'),
        c.Rule('device_auto_ref', r'(?<![\w])auto& (\w+) = ', r'device auto& \1 = ',
               r'\bdevice auto& (\w+) = ', r'auto& \1 = '),
        c.Rule('assert', r'^(\s*)assert\((.*)\);$', r'\1ctx->bad |= !(\2);',
               r'^(\s*)ctx->bad \|= !\((.*)\);$', r'\1assert(\2);'),
        c.Rule('fp_zero', r'^(\s*)(x\d+) = 0;$', r'\1\2 = Fp(0);',
               r'^(\s*)(x\d+) = Fp\(0\);$', r'\1\2 = 0;'),
        c.Rule('trap', r'^(\s*)if \(c1_bad\) __trap\(\);$', r'\1ctx->bad |= c1_bad;',
               r'^(\s*)ctx->bad \|= c1_bad;$', r'\1if (c1_bad) __trap();'),
    ]


# Constructs that must not survive translation.
RESIDUALS = [
    (r'__device__|__host__|__global__|__noinline__|__forceinline__|__trap|__launch_bounds__',
     'CUDA qualifier/intrinsic'),
    (r'\bvoid\* ctx\b', 'untyped ctx'),
    (r'(?<!device )(?<![\w*])\bauto& ', 'reference without address space'),
    (r'(?<!device )(?<!const device )(?<![\w*])\bFp\* ', 'Fp pointer without address space'),
    (r'^\s*assert\(', 'assert'),
    (r'^\s*x\d+ = 0;', 'ambiguous `= 0` on an Fp'),
    (r'extern\.cuh|<cuda|<thrust|cudaStream|size_t', 'CUDA header/type'),
    (r'\bprintf\b', 'printf'),
]

PRELUDE = """\
// Translated from kernels/cuda/%s.cu by kernels/cuda/cuda2metal_steps.py (Metal port item C2);
// never edit by hand. Compile with -I build_kernel/kernels/metal -I recursion-sys/kernels/metal.
// The step functions take `thread %s* ctx`; asserts record into ctx->bad, which the kernel at
// the end of this file ORs into its fault buffer (plan 2.9).
// zirgen emits every constant of a step function up front, most unused in any one arm.
#pragma clang diagnostic ignored "-Wunused-variable"
"""


def translate(name, src):
    """Returns (metal_text, counts)."""
    cfg = FILES[name]
    c.check_no_markers(src, name)
    counts = c.Counter()
    out = c.apply_rules(src, rules_for(cfg['ctx']), counts)
    # Tallies of constructs that pass through.
    counts.add('tally.assert_msg', len(re.findall(r'^\s*ctx->bad \|= !\(.*&& ".*"\);$', out,
                                                     re.M)))
    counts.add('tally.extern_call', len(re.findall(r'\bextern_\w+\(\s*ctx,', out)))
    counts.add('tally.c1_bad', len(re.findall(r'\bc1_bad\b', out)))
    # Prelude right before the include, kernel wrapper at the end.
    inc = '#include "extern.h"\n'
    if out.count(inc) != 1:
        raise c.TranslateError('%s: expected exactly one #include "extern.h"' % name)
    out = out.replace(inc, c.gen_block(PRELUDE % (name, cfg['ctx'])) + inc)
    if not out.endswith('\n'):
        raise c.TranslateError('%s: input does not end with a newline' % name)
    out += '\n' + c.gen_block(cfg['wrapper'])
    counts.add('wrapper')
    c.residual_scan(name, out, RESIDUALS)
    return out, counts


def untranslate(name, text):
    """The inverse of translate (minus the generated blocks)."""
    cfg = FILES[name]
    body = c.strip_gen_blocks(text)
    if not body.endswith('\n\n'):
        raise c.TranslateError('%s: unexpected tail before the wrapper block' % name)
    body = body[:-1]  # the blank line translate() put before the wrapper block
    return c.unapply_rules(body, rules_for(cfg['ctx']))


def read_source(name, step_exec_src=None):
    """The CUDA input of `name`: step_exec in its split form (see the module docstring)."""
    if name != 'step_exec':
        return c.read(os.path.join(c.CUDA_DIR, name + '.cu'))
    if step_exec_src:
        return c.read(step_exec_src)
    try:
        return split_step_exec_metal.split(c.read(os.path.join(c.CUDA_DIR, 'step_exec.cu')))
    except split_step_exec_metal.SplitError as e:
        raise c.TranslateError('step_exec.cu: split_step_exec_metal.py: %s' % e)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('-o', '--outdir')
    ap.add_argument('--check', action='store_true',
                    help='round trip + pins + residuals; compare with OUTDIR files if present')
    ap.add_argument('--no-pin', action='store_true', help='report count mismatches only')
    ap.add_argument('--compile', action='store_true', help='compile each output with xcrun')
    ap.add_argument('--metallib', help='with --compile: link the .air files into this metallib')
    ap.add_argument('--define', action='append', default=[], help='extra -D for --compile')
    ap.add_argument('--only', action='append', choices=sorted(FILES), help='subset of files')
    ap.add_argument('--list-kernels', action='store_true')
    ap.add_argument('--step-exec-src', metavar='SPLIT_CU',
                    help='the split step_exec.cu from split_step_exec_metal.py (build.rs passes '
                         '$OUT_DIR/split/step_exec.cu); default: split kernels/cuda/step_exec.cu '
                         'in memory')
    ap.add_argument('-q', '--quiet', action='store_true')
    a = ap.parse_args(argv)

    if a.list_kernels:
        print('\n'.join(KERNEL_NAMES))
        return 0
    if not a.outdir and not a.check:
        ap.error('-o OUTDIR is required unless --check')
    if a.compile and not a.outdir:
        ap.error('--compile needs -o OUTDIR')

    names = a.only or list(FILES)
    log = (lambda *x: None) if a.quiet else print
    airs = []
    mismatches = []
    for name in names:
        src = read_source(name, a.step_exec_src)
        out, counts = translate(name, src)
        mismatches += c.check_pins(name, counts, PINNED[name], strict=not a.no_pin)
        if a.check:
            back = untranslate(name, out)
            if back != src:
                i = next((k for k in range(min(len(back), len(src))) if back[k] != src[k]),
                         min(len(back), len(src)))
                raise c.TranslateError('%s: round trip differs from the CUDA source at %s'
                                       % (name, c.where(src, i)))
        status = None
        dst = os.path.join(a.outdir, name + '.metal') if a.outdir else None
        if dst:
            status = c.write_or_check(dst, out, a.check)
        log('%s: %s%s%s' % (name, ', '.join('%s=%d' % kv for kv in counts.items()),
                            ' round-trip=ok' if a.check else '',
                            (' -> %s (%s)' % (dst, status)) if dst else ''))
        if a.compile:
            air = os.path.join(a.outdir, name + '.air')
            dt, err = c.compile_metal(dst, air, defines=a.define)
            warns = [l for l in err.splitlines() if 'warning:' in l]
            log('  compiled %s in %.1f s, %d warning lines' % (os.path.basename(air), dt,
                                                                  len(warns)))
            for w in warns[:10]:
                log('    ' + w)
            airs.append(air)
    for name in SKIPPED:
        log('%s: skipped (empty step function, no kernel calls it)' % name)
    if a.metallib:
        dt = c.link_metallib(airs, a.metallib)
        log('linked %s in %.1f s' % (a.metallib, dt))
    if mismatches:
        log('pin mismatches (--no-pin):\n  ' + '\n  '.join(mismatches))
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except c.TranslateError as e:
        print('cuda2metal_steps.py: error: %s' % e, file=sys.stderr)
        sys.exit(1)
